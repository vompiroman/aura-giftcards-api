  assert.equal(await apply(u,false),"PENDING");
  await assert.rejects(()=>apply(u,false),/PARTNER_ALREADY_APPLIED/);
  await assert.rejects(()=>scalar("select public.begin_wallet_deposit($1,$2,3000)",[u,randomUUID()]),/PARTNER_NOT_APPROVED/);
  const review=(application,status)=>scalar("select public.review_partner_application($1,$2,$3,$4)",[application,admin,status,"fixture"]);
  const latest=()=>scalar("select id from public.partner_applications where user_id=$1 order by submitted_at desc limit 1",[u]);
  assert.equal(await review(await latest(),"REJECTED"),true);
  assert.equal((await state()).partner_status,"REJECTED");
  assert.equal(await apply(u,false),"PENDING");
  const application=await latest();
  assert.equal(await review(application,"APPROVED"),true);
  assert.equal(await review(application,"REJECTED"),false);
  assert.equal(await apply(other,true),"APPROVED");
  const deposit=async (amount,invoice,key=randomUUID())=>{
    const tx=await scalar("select public.begin_wallet_deposit($1,$2,$3)",[u,key,amount]);
    assert.equal(tx.create_invoice,true);
    await q("update public.wallet_transactions set provider_invoice_id=$2 where id=$1",[tx.id,invoice]);
    const repeat=await scalar("select public.begin_wallet_deposit($1,$2,$3)",[u,key,amount]);
    assert.equal(repeat.id,tx.id); assert.equal(repeat.create_invoice,false);
    return tx.id;
  };
  const observe=(id,invoice,status,amount)=>scalar("select public.observe_wallet_deposit($1,$2,$3,$4)",[id,invoice,status,amount]);
  const d1=await deposit(1500,"invoice-1");
  assert.equal(await observe(d1,"invoice-1","paid",null),"AMOUNT_MISMATCH");
  assert.equal(await observe(d1,"invoice-1","paid",1499),"AMOUNT_MISMATCH");
  await assert.rejects(()=>observe(d1,"wrong","paid",1500),/WALLET_INVOICE_MISMATCH/);
  await Promise.all([observe(d1,"invoice-1","paid",1500),observe(d1,"invoice-1","paid",1500)]);
  const d2=await deposit(1500,"invoice-2");
  await observe(d2,"invoice-2","paid",1500);
  assert.deepEqual(await state(),{partner_status:"APPROVED",wallet_balance:"3000.00",total_spent:"0.00",has_unlocked_tiers:false,partner_tier:"LOCKED"});
  const d3=await deposit(3000,"invoice-3");
  await observe(d3,"invoice-3","failed",null);
  await observe(d3,"invoice-3","paid",3000);
  assert.equal((await state()).partner_tier,"STARTER");
  const order=(id,subtotal,expected,{key=randomUUID(),wallet=true,promo=null,discount=0,name="Netflix Premium 1 mois"}={})=>scalar(
    "select public.create_partner_order($1,$2,$3,$4,$5,$6)",[u,key,{order_id:id,assigned_email:userEmail,items:[{name,quantity:1}],
      subtotal_amount:subtotal,discount_amount:discount,promo_code_id:promo,marketing_consent:false},wallet,expected,"fixture"]);
  const key=randomUUID();
  const [original,replay]=await Promise.all([order("ORD-wallet-one",2000,2000,{key}),order("ORD-wallet-one",2000,2000,{key})]);
  assert.equal(original.payment_status,"paid");
  assert.equal(replay.replayed,true);
  assert.equal((await state()).partner_tier,"BRONZE");
  await assert.rejects(()=>order("ORD-wallet-one",2000,2000,{key,name:"Different"}),/PARTNER_REQUEST_CONFLICT/);
  await assert.rejects(()=>order("ORD-stale-price",1000,1000),/PARTNER_QUOTE_CHANGED/);
  await assert.rejects(()=>order("ORD-insufficient",8000,7600),/WALLET_INSUFFICIENT_BALANCE/);
  await assert.rejects(()=>order("ORD-promo-rollback",1000,800,{promo:randomUUID(),discount:200}),/PARTNER_PROMO_UNAVAILABLE/);
  assert.equal(await scalar("select count(*)::int from public.orders"),1);
  const attempts=await Promise.allSettled([order("ORD-parallel-1",4000,3800),order("ORD-parallel-2",4000,3800)]);
  assert.equal(attempts.filter(a=>a.status==="fulfilled").length,1);
  assert.equal((await state()).partner_tier,"SILVER");
