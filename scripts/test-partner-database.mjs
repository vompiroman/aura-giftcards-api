  assert.equal(Number((await state()).total_spent),10300);
  assert.equal(Number((await state()).wallet_balance),200);
  const paidId=attempts.find(a=>a.status==="fulfilled").value.order_id;
  const refund=()=>scalar("select public.refund_partner_wallet_order($1)",[paidId]);
  assert.equal(await refund(),true); assert.equal(await refund(),false);
  assert.equal(Number((await state()).wallet_balance),4000);
  assert.equal(Number((await state()).total_spent),6500);
  assert.equal((await state()).partner_tier,"SILVER");
  assert.equal((await state()).has_unlocked_tiers,true);
  await assert.rejects(()=>q("update public.orders set status='pending' where order_id=$1",[paidId]),/WALLET_ORDER_REFUNDED/);
  const ledger=await q("select kind,count(*)::int as count from public.wallet_transactions group by kind order by kind");
  assert.deepEqual(ledger,[{kind:"DEPOSIT",count:3},{kind:"PURCHASE",count:2},{kind:"REFUND",count:1}]);
  assert.equal(Number((await state(other)).wallet_balance),0);
  await db.exec("reset role");
  await db.exec(`insert into public.inventory(assigned_order_id,is_used,service,account_email) values
    (null,false,'Netflix','one@example.invalid'),(null,false,'NETFLIX','ONE@example.invalid'),
    (null,false,'Netflix','two@example.invalid'),('used',true,'Netflix','used@example.invalid'),
    (null,false,'Spotify','other@example.invalid')`);
